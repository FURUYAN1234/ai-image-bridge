inline const wchar_t* tr(const wchar_t* text){if(uiLanguage)for(const auto& t:translations)if(wcscmp(text,t.ja)==0)return t.en;return text;}
// Only developer-authored error messages are localized here, never user input or filenames.
inline std::wstring localizeError(std::wstring text){
    if(!uiLanguage)return text;
    static const auto ordered=[](){std::vector<Translation> v(std::begin(translations),std::end(translations));std::stable_sort(v.begin(),v.end(),[](const auto& a,const auto& b){return wcslen(a.ja)>wcslen(b.ja);});return v;}();
    for(const auto& t:ordered){size_t at=0,n=wcslen(t.ja);while(n&&(at=text.find(t.ja,at))!=std::wstring::npos){text.replace(at,n,t.en);at+=wcslen(t.en);}}
    return text;
}
