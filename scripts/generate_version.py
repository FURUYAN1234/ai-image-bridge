"""Generate runtime/RC version constants from VERSION; --check rejects drift."""
from pathlib import Path
import argparse,re
ROOT=Path(__file__).resolve().parents[1]
def expected_header(root=ROOT):
 version=(root/'VERSION').read_text(encoding='utf-8').strip()
 if not re.fullmatch(r'\d+\.\d+\.\d+',version): raise ValueError('Invalid VERSION')
 return ('// Generated by scripts/generate_version.py from VERSION. Do not edit.\n#pragma once\n'
  +f'#define AIB_VERSION_TEXT "{version}"\n#define AIB_VERSION_WIDE L"{version}"\n'
  +f'#define AIB_TITLE_TEXT "AI Image Bridge {version}"\n#define AIB_TITLE_WIDE L"AI Image Bridge {version}"\n').encode('utf-8')
def check_runtime(root=ROOT):
 if (root/'src/generated_version.h').read_bytes()!=expected_header(root): raise ValueError('Stale generated runtime version header')
 for path in (root/'src').rglob('*'):
  if path.suffix not in ('.cpp','.h','.rc') or path.name=='generated_version.h': continue
  if re.search(r'(?<![\w.])\d+\.\d+\.\d+(?![\w.])',path.read_text(encoding='utf-8')):raise ValueError('Hardcoded runtime version: '+str(path.relative_to(root)))
 source=(root/'src/ui.cpp').read_text(encoding='utf-8');rc=(root/'src/editor.rc').read_text(encoding='utf-8')
 for required in ['std::wstring(AIB_TITLE_WIDE L" | ")', 'std::wstring(AIB_VERSION_WIDE L" / ")', '{"version",AIB_VERSION_TEXT}']:
  if required not in source:raise ValueError('Runtime version consumer missing: '+required)
 if 'L"CloudImageFilter/" AIB_VERSION_WIDE' not in (root/'src/core.cpp').read_text(encoding='utf-8'):raise ValueError('User agent version consumer missing')
 if 'CAPTION AIB_TITLE_TEXT' not in rc or 'LTEXT AIB_VERSION_TEXT,203' not in rc:raise ValueError('Resource version consumer missing')
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 if args.check:check_runtime()
 else:(ROOT/'src/generated_version.h').write_bytes(expected_header())
